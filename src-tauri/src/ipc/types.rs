use serde::{Deserialize, Serialize};
use ts_rs::TS;

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(rename_all = "snake_case")]
#[ts(export)]
pub enum MicState {
    Off,
    Muted,
    Standby,
    Capturing,
    Unavailable,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(rename_all = "snake_case")]
#[ts(export)]
pub enum AssistantPhase {
    Idle,
    Listening,
    Transcribing,
    Thinking,
    AwaitingApproval,
    Acting,
    Speaking,
    Error,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(rename_all = "snake_case")]
#[ts(export)]
pub enum NetworkState {
    Online,
    Offline,
    Unknown,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(rename_all = "SCREAMING_SNAKE_CASE")]
#[ts(export)]
pub enum ErrorCode {
    MicPermissionDenied,
    DeviceLost,
    ModelMissing,
    ModelChecksum,
    ProviderAuth,
    ProviderRateLimit,
    ProviderUnavailable,
    NetworkOffline,
    SpendCapReached,
    ToolDenied,
    ToolTimeout,
    ToolFailed,
    Internal,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(rename_all = "snake_case")]
#[ts(export)]
pub enum Risk {
    Medium,
    High,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(rename_all = "camelCase")]
#[ts(export)]
pub struct JarvisError {
    pub code: ErrorCode,
    pub message: String,
    pub retryable: bool,
    pub request_id: Option<String>,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(rename_all = "camelCase")]
#[ts(export)]
pub struct ApprovalRequest {
    pub approval_id: String,
    pub request_id: String,
    pub tool: String,
    pub risk: Risk,
    /// Human sentence generated by the backend, never by the model.
    pub summary: String,
    pub targets: Vec<String>,
    /// SHA-256 of canonical args; the approval binds to it.
    pub args_digest: String,
    #[ts(type = "number")]
    pub expires_at: u64,
    pub allow_voice: bool,
    pub tainted: bool,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(rename_all = "camelCase")]
#[ts(export)]
pub struct Snapshot {
    #[ts(type = "number")]
    pub seq: u64,
    pub mic: MicState,
    pub phase: AssistantPhase,
    pub active_request_id: Option<String>,
    pub network: NetworkState,
    /// True while data is leaving the machine.
    pub cloud_in_use: bool,
    pub pending_approvals: Vec<ApprovalRequest>,
    pub last_error: Option<JarvisError>,
}

impl Snapshot {
    pub fn initial() -> Self {
        Self {
            seq: 0,
            mic: MicState::Off,
            phase: AssistantPhase::Idle,
            active_request_id: None,
            network: NetworkState::Unknown,
            cloud_in_use: false,
            pending_approvals: vec![],
            last_error: None,
        }
    }
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(rename_all = "camelCase")]
#[ts(export)]
pub struct PingResponse {
    pub pong: bool,
    pub protocol_version: u32,
    pub app_version: String,
}
