/// Partial update. For the caps: omit the field to leave it unchanged, send `null`
/// to clear the cap, send a number to set it.
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
#[ts(export)]
pub struct SettingsPatch {
    #[serde(default, skip_serializing_if = "Option::is_none")]
    #[ts(optional)]
    pub model: Option<String>,
    #[serde(default)]
    #[serde(deserialize_with = "tri_state")]
    #[serde(skip_serializing_if = "Option::is_none")]
    #[ts(optional, type = "number | null")]
    pub daily_cap_micro_usd: Option<Option<u64>>,
    #[serde(default)]
    #[serde(deserialize_with = "tri_state")]
    #[serde(skip_serializing_if = "Option::is_none")]
    #[ts(optional, type = "number | null")]
    pub monthly_cap_micro_usd: Option<Option<u64>>,
    /// Replaces the whole list. Each folder is canonicalised and must exist.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    #[ts(optional)]
    pub allowed_folders: Option<Vec<String>>,
    /// Replaces the whole list. Only ids returned by `apps_installed` are accepted; the
    /// `name` is taken from that list, not from the patch.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    #[ts(optional)]
    pub allowed_apps: Option<Vec<AllowedApp>>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    #[ts(optional)]
    pub auto_allow_medium: Option<bool>,
}

/// Distinguishes a missing field (`None`) from an explicit `null` (`Some(None)`).
fn tri_state<'de, D>(d: D) -> Result<Option<Option<u64>>, D::Error>
where
    D: serde::Deserializer<'de>,
{
    Option::<u64>::deserialize(d).map(Some)
}

